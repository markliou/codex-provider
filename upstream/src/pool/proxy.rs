/// Makes a request the Codex backend would reject into the closest one it
/// accepts, and reports whether the client asked for a non-streaming answer
/// that has to be assembled from the stream. The Codex backend only streams,
/// only accepts store=false and list input, and has no system role. A request
/// that already has that shape, which is every request a native Codex sends,
/// is returned byte for byte, so only foreign requests are changed and Codex
/// requests stay native. The compact endpoint is not a Responses stream and
/// is forwarded as sent.
pub fn codex_backend_request_body(endpoint: &str, raw: &Bytes) -> (Bytes, bool) {
    if endpoint.ends_with("/responses/compact") {
        return (raw.clone(), false);
    }
    let Ok(mut payload) = serde_json::from_slice::<Map<String, Value>>(raw) else {
        return (raw.clone(), false);
    };
    let mut changed = false;
    let mut aggregate = false;
    if let Some(Value::String(text)) = payload.get("input") {
        let text = text.clone();
        payload.insert(
            "input".to_string(),
            serde_json::json!([{"type": "message", "role": "user", "content": [{"type": "input_text", "text": text}]}]),
        );
        changed = true;
    }
    if payload.get("stream").and_then(Value::as_bool) != Some(true) {
        payload.insert("stream".to_string(), Value::Bool(true));
        aggregate = true;
        changed = true;
    }
    if payload.get("store").and_then(Value::as_bool) != Some(false) {
        payload.insert("store".to_string(), Value::Bool(false));
        changed = true;
    }
    for field in CODEX_BACKEND_UNSUPPORTED_FIELDS {
        if payload.remove(*field).is_some() {
            changed = true;
        }
    }
    if let Some(Value::Array(input)) = payload.get_mut("input") {
        for item in input.iter_mut() {
            if let Some(item) = item.as_object_mut()
                && item.get("role").and_then(Value::as_str) == Some("system")
            {
                item.insert("role".to_string(), Value::String("developer".to_string()));
                changed = true;
            }
        }
    }
    if !changed {
        return (raw.clone(), false);
    }
    (
        Bytes::from(gojson::marshal(&Value::Object(payload))),
        aggregate,
    )
}

/// The x-codex-routing-hint a native Codex signed in with ChatGPT attaches to
/// every Codex-backend request ("model=<model>", plus ";tier=<service_tier>"
/// when one is set), except guardian reviewer requests. Upstream uses it to
/// route the request to the right serving pool before it reads the body. A
/// custom-provider Codex client never sends it, so the pool adds exactly the
/// value Codex itself would have sent; a hint the client did send wins.
pub fn codex_routing_hint(body: &[u8], inbound: &HeaderMap) -> String {
    if !header(inbound, "x-codex-routing-hint").trim().is_empty()
        || header(inbound, "x-codex-guardian")
            .trim()
            .eq_ignore_ascii_case("reviewer")
    {
        return String::new();
    }
    let Ok(fields) = serde_json::from_slice::<Map<String, Value>>(body) else {
        return String::new();
    };
    // Go decodes into string fields: a non-string model fails the decode.
    let field = |name: &str| match fields.get(name) {
        None | Some(Value::Null) => Some(String::new()),
        Some(Value::String(text)) => Some(text.trim().to_string()),
        Some(_) => None,
    };
    let (Some(model), Some(tier)) = (field("model"), field("service_tier")) else {
        return String::new();
    };
    if model.is_empty() {
        return String::new();
    }
    if tier.is_empty() {
        format!("model={model}")
    } else {
        format!("model={model};tier={tier}")
    }
}

/// Relays the client's X-Codex-Turn-State only to the account that issued
/// it. A native Codex never presents one account's turn token to another
/// account, so after a failover, a lineage move, or with no known issuer the
/// header is withheld and the attempt looks like a native request that starts
/// a turn fresh. Returns the headers to forward and the disposition for local
/// telemetry ("relayed", "withheld", or "" when absent).
pub fn turn_state_for_attempt(
    inbound: &HeaderMap,
    issuer_account_id: &str,
    candidate_account_id: &str,
) -> (HeaderMap, &'static str) {
    if header(inbound, "x-codex-turn-state").trim().is_empty() {
        return (inbound.clone(), "");
    }
    if !issuer_account_id.is_empty() && issuer_account_id == candidate_account_id {
        return (inbound.clone(), "relayed");
    }
    let mut withheld = inbound.clone();
    withheld.remove("x-codex-turn-state");
    (withheld, "withheld")
}

pub fn retry_after_or_default(value: &str, fallback: Duration) -> Duration {
    match value.parse::<u64>() {
        Ok(seconds) if seconds > 0 => Duration::from_secs(seconds),
        _ => fallback,
    }
}

fn delta(duration: Duration) -> TimeDelta {
    TimeDelta::from_std(duration).unwrap_or_else(|_| TimeDelta::zero())
}

/// Maps an in-stream failure onto the status the non-streaming path already
/// routes on: capacity moves to another identity like a 429, an auth failure
/// is the account's credential, a request error is the caller's, and anything
/// else is an upstream fault.
pub fn codex_stream_failure_status(class: &str) -> StatusCode {
    match class {
        "capacity" => StatusCode::TOO_MANY_REQUESTS,
        "authentication" => StatusCode::UNAUTHORIZED,
        "request" => StatusCode::BAD_REQUEST,
        _ => StatusCode::BAD_GATEWAY,
    }
}

pub fn is_streaming(headers: &HeaderMap) -> bool {
    header(headers, "content-type")
        .to_lowercase()
        .contains("text/event-stream")
}

/// Answers a client that asked for a non-streaming response: reads the Codex
/// backend's stream to its terminal event and returns the single Responses
/// JSON document, or an error status the non-streaming failover already
/// understands. The completed event can arrive with an empty output list, so
/// the output is rebuilt from the items the stream reported. Upstream
/// response headers (request id, turn state, model) are kept.
pub async fn aggregate_codex_stream(response: UpstreamResponse) -> UpstreamResponse {
    if !response.status.is_success() || !is_streaming(&response.headers) {
        return response;
    }
    let mut headers = response.headers.clone();
    let reply = |headers: &mut HeaderMap, status: StatusCode, payload: Value| {
        headers.insert(
            http::header::CONTENT_TYPE,
            http::HeaderValue::from_static("application/json"),
        );
        headers.remove(http::header::CONTENT_LENGTH);
        UpstreamResponse {
            status,
            headers: headers.clone(),
            body: super::stream::byte_stream_from(gojson::marshal(&payload)),
        }
    };
    let mut reader = SseReader::new(response.body);
    let mut by_index: std::collections::BTreeMap<i64, Value> = std::collections::BTreeMap::new();
    let mut in_order: Vec<Value> = Vec::new();
    let mut read_total = 0usize;
    loop {
        let (block, end) = reader.read_block().await;
        read_total += block.len();
        let text = String::from_utf8_lossy(&block).into_owned();
        if !text.trim().is_empty() {
            let event_type = super::response_info::response_event_type_from_sse_block(&text);
            let (_, data) = super::response_info::sse_block_event_and_data(&text);
            let event: Map<String, Value> = serde_json::from_str(&data).unwrap_or_default();
            match event_type.as_str() {
                "response.output_item.done" => {
                    if let Some(item) = event.get("item") {
                        match event.get("output_index").and_then(Value::as_f64) {
                            #[allow(clippy::cast_possible_truncation)]
                            Some(index) => {
                                by_index.insert(index as i64, item.clone());
                            }
                            None => in_order.push(item.clone()),
                        }
                    }
                }
                "response.completed" | "response.incomplete" => {
                    let Some(Value::Object(mut completed)) = event.get("response").cloned() else {
                        return reply(
                            &mut headers,
                            StatusCode::BAD_GATEWAY,
                            serde_json::json!({"error": {"code": "bad_gateway", "message": "upstream completed without a response"}}),
                        );
                    };
                    let empty = completed
                        .get("output")
                        .and_then(Value::as_array)
                        .is_none_or(Vec::is_empty);
                    if empty {
                        let rebuilt: Vec<Value> = by_index
                            .values()
                            .cloned()
                            .chain(in_order.iter().cloned())
                            .collect();
                        completed.insert("output".to_string(), Value::Array(rebuilt));
                    }
                    return reply(&mut headers, StatusCode::OK, Value::Object(completed));
                }
                "response.failed" | "error" => {
                    let mut error_payload = event.get("error").and_then(Value::as_object).cloned();
                    if error_payload.is_none() {
                        error_payload = event
                            .get("response")
                            .and_then(|response| response.get("error"))
                            .and_then(Value::as_object)
                            .cloned();
                    }
                    let error_payload = error_payload.unwrap_or_else(|| {
                        let mut fallback = Map::new();
                        fallback.insert(
                            "code".into(),
                            Value::String(plan::claim_string(&event, "code").to_string()),
                        );
                        fallback.insert(
                            "message".into(),
                            Value::String(plan::claim_string(&event, "message").to_string()),
                        );
                        fallback
                    });
                    let status = codex_stream_failure_status(terminal_failure_class(
                        &event_type,
                        &terminal_error_code(&error_payload),
                    ));
                    return reply(
                        &mut headers,
                        status,
                        serde_json::json!({"error": error_payload}),
                    );
                }
                _ => {}
            }
        }
        if end.is_some() || read_total > (64 << 20) {
            return reply(
                &mut headers,
                StatusCode::BAD_GATEWAY,
                serde_json::json!({"error": {"code": "bad_gateway", "message": "upstream stream ended before the response completed"}}),
            );
        }
    }
}

impl App {
    /// Whether the pool itself talks to the Codex backend with the account's
    /// ChatGPT credential, as a native Codex CLI does.
    pub fn uses_codex_backend_directly(candidate: &Account) -> bool {
        is_codex_device_auth(candidate) && candidate.upstream_api_key.is_empty()
    }

    /// The endpoint and body for one account, and whether the answer must be
    /// converted to a chat completion.
    pub fn prepare_upstream_request(
        &self,
        candidate: &Account,
        body: &Bytes,
        chat: bool,
    ) -> Result<(String, Bytes, bool), String> {
        let mut base = candidate
            .upstream_base_url
            .trim_end_matches('/')
            .to_string();
        if base.is_empty() && is_codex_device_auth(candidate) {
            base = self.settings.codex_responses_base_url();
        }
        if base.is_empty() {
            return Err("selected account has no upstreamBaseUrl".to_string());
        }
        if !chat || plan::normal_wire_api(&candidate.wire_api) == "chat_completions" {
            let path = if chat {
                "/chat/completions"
            } else {
                "/responses"
            };
            return Ok((format!("{base}{path}"), body.clone(), false));
        }
        let chat_request: Map<String, Value> =
            serde_json::from_slice(body).map_err(|error| error.to_string())?;
        let input: Vec<Value> = chat_request
            .get("messages")
            .and_then(Value::as_array)
            .map(|messages| {
                messages
                    .iter()
                    .map(|message| {
                        serde_json::json!({
                            "role": message.get("role").cloned().unwrap_or(Value::Null),
                            "content": message.get("content").cloned().unwrap_or(Value::Null),
                        })
                    })
                    .collect()
            })
            .unwrap_or_default();
        let mut request = Map::new();
        request.insert(
            "model".into(),
            chat_request.get("model").cloned().unwrap_or(Value::Null),
        );
        request.insert("input".into(), Value::Array(input));
        if chat_request.get("stream").and_then(Value::as_bool) == Some(true) {
            request.insert("stream".into(), Value::Bool(true));
        }
        for name in ["prompt_cache_key", "prompt_cache_retention"] {
            if let Some(value) = chat_request.get(name) {
                request.insert(name.into(), value.clone());
            }
        }
        Ok((
            format!("{base}/responses"),
            Bytes::from(gojson::marshal(&Value::Object(request))),
            true,
        ))
    }

    /// Sends one attempt to the account, refreshing a direct Codex account's
    /// token first and once more on a 401, as a native Codex does.
    pub async fn forward(
        &self,
        candidate: &Account,
        endpoint: &str,
        body: Bytes,
        inbound: &HeaderMap,
    ) -> Result<UpstreamResponse, ForwardError> {
        if !Self::uses_codex_backend_directly(candidate) {
            return self
                .forward_once(candidate, endpoint, body, inbound, None)
                .await;
        }
        let (body, aggregate) = codex_backend_request_body(endpoint, &body);
        let auth = self
            .refreshed_codex_auth(candidate)
            .await
            .map_err(auth_error)?;
        let mut response = self
            .forward_once(candidate, endpoint, body.clone(), inbound, Some(&auth))
            .await?;
        if response.status == StatusCode::UNAUTHORIZED {
            // A native Codex answers a 401 by refreshing its token and
            // retrying once before treating the credential as bad. The pool
            // owns this account's token in direct mode, so it does the same:
            // an access token upstream stopped accepting before its expiry must
            // not fail the account over or send it to repair. Only a second
            // 401, or a refresh that cannot produce a new token, reaches the
            // caller's auth-failure handling.
            let rejected = super::credentials::read_body(response, MAX_REQUEST_BODY)
                .await
                .unwrap_or_default();
            let refreshed = self
                .refresh_codex_auth_after_rejection(candidate, &auth.access_token)
                .await;
            response = match refreshed {
                Ok(refreshed)
                    if !refreshed.access_token.is_empty()
                        && refreshed.access_token != auth.access_token =>
                {
                    self.forward_once(candidate, endpoint, body, inbound, Some(&refreshed))
                        .await?
                }
                _ => UpstreamResponse {
                    status: StatusCode::UNAUTHORIZED,
                    headers: HeaderMap::new(),
                    body: super::stream::byte_stream_from(rejected),
                },
            };
        }
        // The Codex backend answers a Responses stream with no Content-Type
        // at all (a native Codex reads the stream regardless). Every request
        // sent to /responses streams, so a success without a Content-Type is
        // that stream. Without this the pool took it for a plain body: the
        // pre-commit window, and with it the capacity retry on another
        // account, never ran, usage and terminal events went unrecorded, and a
        // non-streaming client got raw SSE.
        if endpoint.ends_with("/responses")
            && response.status.is_success()
            && header(&response.headers, "content-type").trim().is_empty()
        {
            response.headers.insert(
                http::header::CONTENT_TYPE,
                http::HeaderValue::from_static("text/event-stream"),
            );
        }
        if !aggregate {
            return Ok(response);
        }
        Ok(aggregate_codex_stream(response).await)
    }

    /// One send: the account's credential and identity, the client's Codex
    /// headers, and Codex's client. The headers are gathered as Go's request
    /// headers and handed over in the order Go wrote them on its hop to
    /// codex-upstream, then placed in native order by the transport.
    async fn forward_once(
        &self,
        candidate: &Account,
        endpoint: &str,
        mut body: Bytes,
        inbound: &HeaderMap,
        auth: Option<&super::metadata::CodexAuthInfo>,
    ) -> Result<UpstreamResponse, ForwardError> {
        self.note_client_agent(&candidate.id, inbound);
        self.note_account_activity(&candidate.id);
        let direct = Self::uses_codex_backend_directly(candidate);
        // The account presents its own installation id, not the client's
        // (installation_id.rs, SPEC.md 2.3.2).
        let installation = if direct {
            self.presented_installation_id(candidate)
        } else {
            None
        };
        if let Some(id) = &installation {
            let text = String::from_utf8_lossy(&body).into_owned();
            body = Bytes::from(installation_id::with_installation_id(&text, id).into_owned());
        }
        let mut headers = GoHeader::default();
        headers.set("Content-Type", "application/json");
        let accept = header(inbound, "accept");
        if !accept.is_empty() {
            headers.set("Accept", accept);
        }
        for (name, value) in inbound {
            if !relayed_codex_request_header(name.as_str()) {
                continue;
            }
            if let Ok(value) = value.to_str()
                && !value.trim().is_empty()
            {
                headers.add(name.as_str(), value.trim());
            }
        }
        if let Some(id) = &installation {
            let metadata = headers.get("X-Codex-Turn-Metadata").to_string();
            if !metadata.is_empty() {
                headers.set(
                    "X-Codex-Turn-Metadata",
                    &installation_id::turn_metadata_with_installation_id(&metadata, id),
                );
            }
        }
        if !candidate.upstream_api_key.is_empty() {
            headers.set(
                "Authorization",
                &format!("Bearer {}", candidate.upstream_api_key),
            );
        } else if direct {
            let auth = auth.cloned().unwrap_or_default();
            let account_id = if auth.account_id.is_empty() {
                candidate.account_id.clone()
            } else {
                auth.account_id.clone()
            };
            headers.set("Authorization", &format!("Bearer {}", auth.access_token));
            if !account_id.is_empty() {
                headers.set("ChatGPT-Account-ID", &account_id);
            }
            if auth.fedramp {
                headers.set("X-OpenAI-Fedramp", "true");
            }
            let hint = codex_routing_hint(&body, inbound);
            if !hint.is_empty() {
                headers.set("X-Codex-Routing-Hint", &hint);
            }
            let version = codex_client_version(inbound);
            if !version.is_empty() && headers.get("Version").is_empty() {
                headers.set("Version", &version);
            }
        }
        // A native Codex zstd-compresses its Responses requests to the Codex
        // backend; compaction requests are sent uncompressed.
        let compression = if direct && endpoint.ends_with("/responses") {
            RequestCompression::Zstd
        } else {
            RequestCompression::None
        };
        let (request, after) = crate::transport::build_request(
            Method::POST,
            endpoint.to_string(),
            &headers.to_map(),
            body,
            compression,
            None,
        )
        .map_err(ForwardError::Transport)?;
        crate::transport::send_request(&self.transports, request, &after)
            .await
            .map_err(|failure| match failure {
                SendFailure::Timeout => {
                    ForwardError::Transport("codex upstream timeout: upstream timeout".to_string())
                }
                SendFailure::Connection(detail) | SendFailure::Prepare(detail) => {
                    ForwardError::Transport(format!("codex upstream connection: {detail}"))
                }
            })
    }

    /// The account's own installation id; None (the client's passes through)
    /// when it cannot be read or made.
    pub fn presented_installation_id(&self, item: &Account) -> Option<String> {
        let home = self.read().account_codex_home(&item.id);
        match installation_id::resolve(&home, super::crypto::random_uuid) {
            Ok(id) => Some(id),
            Err(error) => {
                self.logger.printf(&format!(
                    "installation id unavailable for {}: {error}",
                    item.id
                ));
                None
            }
        }
    }

    /// When a request last went to each account sets its quota poll cadence
    /// (quota_schedule.rs).
    pub fn note_account_activity(&self, account_id: &str) {
        let mut activity = self
            .account_activity
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        activity.insert(account_id.to_string(), Timestamp::now());
    }

    pub fn account_in_use(&self, account_id: &str, now: Timestamp) -> bool {
        let activity = self
            .account_activity
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        activity.get(account_id).is_some_and(|last| {
            now.sub(last)
                < TimeDelta::from_std(super::quota_schedule::ACTIVE_WINDOW)
                    .unwrap_or_else(|_| TimeDelta::minutes(30))
        })
    }

    /// The account that served this route's last successful response, the
    /// only account whose turn state Codex can be holding: the client only
    /// ever receives the committed attempt's headers and response.metadata,
    /// and that success is what updates the sticky session.
    pub fn sticky_session_account_id(&self, sticky_key: &str) -> String {
        let now = Timestamp::now();
        let inner = self.read();
        match inner.state.sticky_sessions().get(sticky_key) {
            Some(session) if !inner.sticky_session_expired(session, now) => {
                session.account_id.clone()
            }
            _ => String::new(),
        }
    }
}

fn auth_error(error: CredentialError) -> ForwardError {
    if error.auth_failed {
        ForwardError::Auth(error.message)
    } else {
        ForwardError::Transport(error.message)
    }
}

pub fn safe_header_value(value: &str) -> String {
    value
        .trim()
        .chars()
        .filter(|c| !matches!(*c, '\r' | '\n' | '\0') && (*c >= ' ' || *c == '\t'))
        .collect()
}

fn copy_proxy_response_headers(writer: &mut dyn ResponseWriter, upstream: &HeaderMap) {
    for name in PROXY_RESPONSE_HEADER_ALLOWLIST {
        let value = header(upstream, name);
        if !value.is_empty() {
            set_header(writer, name, value);
        }
    }
}

fn commit_proxy_response_headers(
    writer: &mut dyn ResponseWriter,
    status: StatusCode,
    upstream: &HeaderMap,
) {
    copy_proxy_response_headers(writer, upstream);
    writer.write_header(status);
}

/// What only a native-endpoint client is owed. X-Models-Etag names upstream's
/// catalog, and Codex refetches its catalog when it changes (core
/// session/turn.rs refresh_if_new_etag): through the native endpoint the
/// catalog is upstream's, so withholding it made Codex send fewer catalog
/// requests than a native Codex. A /v1 client's catalog is the pool's own,
/// which carries no ETag, so there it would only make Codex refetch the pool's
/// catalog on every turn.
fn relay_native_codex_response_headers(
    writer: &mut dyn ResponseWriter,
    upstream: &HeaderMap,
    native: bool,
) {
    if !native {
        return;
    }
    let etag = header(upstream, "x-models-etag");
    if !etag.is_empty() {
        set_header(writer, "x-models-etag", etag);
    }
}

async fn copy_proxy_response(
    writer: &mut dyn ResponseWriter,
    response: UpstreamResponse,
    tuning: &super::tuning::Tuning,
) -> Option<ProxyResponseInfo> {
    commit_proxy_response_headers(writer, response.status, &response.headers);
    let streaming = is_streaming(&response.headers);
    let mut reader = SseReader::new(response.body);
    if streaming {
        return Some(copy_streaming_proxy_response(writer, &mut reader, tuning).await);
    }
    let body = reader.read_all(usize::MAX).await.ok()?;
    let mut info = serde_json::from_slice::<Map<String, Value>>(&body)
        .map(|payload| response_info_from_payload(Some(&payload)))
        .unwrap_or_default();
    info.completed_at = Timestamp::now();
    writer.write(&body);
    Some(info)
}

fn output_text(data: &Map<String, Value>) -> String {
    data.get("output")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
        .filter_map(|item| item.get("content").and_then(Value::as_array))
        .flatten()
        .find_map(|part| part.get("text").and_then(Value::as_str))
        .unwrap_or_default()
        .to_string()
}

async fn write_chat_from_response(
    writer: &mut dyn ResponseWriter,
    response: UpstreamResponse,
    model: &str,
    tuning: &super::tuning::Tuning,
) -> Option<ProxyResponseInfo> {
    if !response.status.is_success() {
        return copy_proxy_response(writer, response, tuning).await;
    }
    let body = SseReader::new(response.body)
        .read_all(usize::MAX)
        .await
        .unwrap_or_default();
    let Ok(data) = serde_json::from_slice::<Map<String, Value>>(&body) else {
        write_openai_error(
            writer,
            StatusCode::BAD_GATEWAY,
            "bad_gateway",
            "invalid Responses API payload from upstream",
        );
        return None;
    };
    let text = output_text(&data);
    write_json(
        writer,
        StatusCode::OK,
        &serde_json::json!({
            "id": format!("chatcmpl_{}", super::crypto::random_id()),
            "object": "chat.completion",
            "created": Timestamp::now().unix(),
            "model": model,
            "choices": [{"index": 0, "message": {"role": "assistant", "content": text}, "finish_reason": "stop"}],
        }),
    );
    let mut info = response_info_from_payload(Some(&data));
    info.completed_at = Timestamp::now();
    Some(info)
}

/// Go handleProxy: the provider request path for /v1/responses,
/// /v1/responses/compact, /v1/chat/completions and the native endpoint's
/// Responses paths.
pub async fn handle_proxy(
    app: &Arc<App>,
    request: ProxyRequest,
    writer: Box<dyn ResponseWriter>,
    chat: bool,
) {
    let mut writer = writer;
    if request.body.len() > MAX_REQUEST_BODY {
        write_openai_error(
            writer.as_mut(),
            StatusCode::BAD_REQUEST,
            "invalid_request",
            "request body is invalid or too large",
        );
        return;
    }
    let Ok(mut payload) = serde_json::from_slice::<Map<String, Value>>(&request.body) else {
        write_openai_error(
            writer.as_mut(),
            StatusCode::BAD_REQUEST,
            "invalid_request",
            "request body must be JSON",
        );
        return;
    };
    let streaming = payload
        .get("stream")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    if streaming && !chat {
        let mut early = EarlyStreamWriter::new(writer, app.tuning.precommit_max_hold, &app.tuning);
        proxy(app, &request, &mut payload, &mut early, chat, streaming).await;
        early.finish().await;
    } else {
        proxy(
            app,
            &request,
            &mut payload,
            writer.as_mut(),
            chat,
            streaming,
        )
        .await;
    }
}

async fn proxy(
    app: &Arc<App>,
    request: &ProxyRequest,
    payload: &mut Map<String, Value>,
    writer: &mut dyn ResponseWriter,
    chat: bool,
    streaming: bool,
) {
    let compact = !chat && request.path.ends_with("/responses/compact");
    let mut requested_model = payload
        .get("model")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_string();
    let (default_model, aliases) = {
        let inner = app.read();
        (
            inner.config.default_model.clone(),
            inner.config.model_aliases().clone(),
        )
    };
    if requested_model.is_empty() {
        requested_model = default_model;
    }
    let (mut model, tier) = parse_model(&requested_model);
    if let Some(alias) = aliases.get(&model) {
        model.clone_from(alias);
    }
    // A request from the native endpoint is already the one Codex sends OpenAI
    // and must reach upstream as Codex wrote it (SPEC.md 2.3.3). The rewrites
    // below adapt custom-provider and foreign requests; applied to a native
    // request, dropHostedToolConflicts removed the image_gen tool a native
    // Codex sends its own backend and re-encoding sorted every key. Routing
    // still reads the model; nothing is written back.
    let native = request.native;
    let original: Option<Map<String, Value>> = (!native).then(|| payload.clone());
    if !native {
        payload.insert("model".into(), Value::String(model.clone()));
        if !chat && !tier.is_empty() && tier != "none" {
            payload.insert("reasoning".into(), serde_json::json!({"effort": tier}));
        }
        drop_hosted_tool_conflicts(payload);
    }
    let facts = RequestFacts {
        headers: &request.headers,
        native,
        websocket: false,
    };
    let api_key = super::server::request_api_key(&request.headers, &request.query);
    let mut route = app.routing_decision(&facts, payload, &model, &api_key);
    if !native {
        app.read().apply_prompt_cache_controls(payload, &route);
    }
    let mut throughput = app.begin_throughput_measurement(streaming);
    // Forward the client's own bytes whenever the pool left the request as it
    // arrived. Re-encoding a decoded map sorts every object's keys, tool
    // parameter schemas included, and rewrites number formatting, so even an
    // untouched request reached upstream in a byte layout no native Codex sends.
    let updated_body = if native || original.as_ref() == Some(&*payload) {
        request.body.clone()
    } else {
        Bytes::from(gojson::marshal(&Value::Object(payload.clone())))
    };
    attempts(
        app,
        request,
        writer,
        chat,
        compact,
        native,
        &model,
        &mut route,
        updated_body,
        &mut throughput,
    )
    .await;
    app.finish_throughput_measurement(&mut throughput);
}

#[allow(clippy::too_many_arguments)]
async fn attempts(
    app: &Arc<App>,
    request: &ProxyRequest,
    writer: &mut dyn ResponseWriter,
    chat: bool,
    compact: bool,
    native: bool,
    model: &str,
    route: &mut super::routing::RoutingDecision,
    updated_body: Bytes,
    throughput: &mut super::outcome::ThroughputMeasurement,
) {
    let cancel = &request.cancel;
    let request_id = request_operational_id(&request.headers);
    let mut failover_from = String::new();
    let mut failover_outcome = String::new();
    let mut excluded: HashMap<String, bool> = HashMap::new();
    // The subset of excluded that refused for capacity alone. Only those may
    // be restored for a later round; an auth or transport failure is not
    // transient and must stay excluded.
    let mut capacity_excluded: HashMap<String, bool> = HashMap::new();
    let mut capacity_retries = 0u32;
    let mut overload_retries = 0u32;
    let mut transport_retries = 0u32;
    let turn_state_issuer = app.sticky_session_account_id(&route.sticky_key);
    let attempt_limit = i64::try_from(app.proxy_attempt_limit()).unwrap_or(i64::MAX);
    let tuning = app.tuning;
    let mut attempt: i64 = 0;
    while attempt < attempt_limit {
        let candidate = match app.select_account_for_route(route, model, &excluded) {
            Ok(candidate) => candidate,
            Err(SelectError::AuthRepairPending) => {
                write_openai_error(
                    writer,
                    StatusCode::SERVICE_UNAVAILABLE,
                    "account_authenticating",
                    "the session account is completing sign-in repair; retry shortly",
                );
                return;
            }
            Err(error) => {
                if !excluded.is_empty() {
                    // At least one upstream was already selected and failed.
                    // Reporting "no eligible account" makes a transient upstream
                    // failure look like pool exhaustion, especially when Pro is
                    // the only real fallback after Plus/Team quota is drained.
                    write_openai_error(
                        writer,
                        StatusCode::BAD_GATEWAY,
                        "bad_gateway",
                        "all eligible upstream accounts failed",
                    );
                    return;
                }
                write_openai_error(
                    writer,
                    StatusCode::SERVICE_UNAVAILABLE,
                    "all_accounts_cooling_down",
                    &error.to_string(),
                );
                return;
            }
        };
        throughput.account_id.clone_from(&candidate.id);
        app.note_session_placement(&route.balance_key, &candidate.id);
        let (mut endpoint, out_body, convert_response) =
            match app.prepare_upstream_request(&candidate, &updated_body, chat) {
                Ok(prepared) => prepared,
                Err(error) => {
                    write_openai_error(writer, StatusCode::BAD_GATEWAY, "bad_gateway", &error);
                    return;
                }
            };
        if compact && App::uses_codex_backend_directly(&candidate) {
            // A native Codex sends remote compaction to the Codex backend's
            // own compact endpoint, not to the Responses stream.
            endpoint.push_str("/compact");
        }
        let (inbound, turn_state) =
            turn_state_for_attempt(&request.headers, &turn_state_issuer, &candidate.id);
        route.client.turn_state = turn_state.to_string();
        let forwarded = tokio::select! {
            result = app.forward(&candidate, &endpoint, out_body, &inbound) => Some(result),
            () = cancel.cancelled() => None,
        };
        let Some(forwarded) = forwarded else {
            // The caller timed out or disconnected. Stop immediately and avoid
            // marking the selected account unhealthy; no upstream failure was
            // confirmed, and persisting one makes later unrelated requests
            // slower.
            throughput.cancelled = true;
            return;
        };
        let response = match forwarded {
            Ok(response) => response,
            Err(error) => {
                let auth = matches!(error, ForwardError::Auth(_));
                if !auth && transport_retries < TRANSPORT_SAME_ACCOUNT_RETRY_LIMIT {
                    transport_retries += 1;
                    app.logger.printf(&format!(
                        "upstream unreachable for {} (try {transport_retries} of {} on this account)",
                        candidate.id,
                        TRANSPORT_SAME_ACCOUNT_RETRY_LIMIT + 1
                    ));
                    if !cancel
                        .sleep(tuning.transport_retry_backoff * (1 << (transport_retries - 1)))
                        .await
                    {
                        throughput.cancelled = true;
                        return;
                    }
                    continue;
                }
                excluded.insert(candidate.id.clone(), true);
                failover_from.clone_from(&candidate.id);
                if auth {
                    // A revoked or invalid device-auth credential must not end
                    // the user request while other upstream accounts are
                    // eligible. Mark it unavailable and continue; selection
                    // also suppresses any local duplicate slot for the same
                    // upstream identity during this attempt.
                    failover_outcome = "auth_failover".to_string();
                    app.mark_account_auth_failure(&candidate.id, model, "account_auth_failed");
                } else {
                    failover_outcome = "transport_failover".to_string();
                    app.mark_failure(
                        &candidate.id,
                        model,
                        "upstream_transport_error",
                        seconds(30),
                    );
                }
                attempt += 1;
                continue;
            }
        };
        let status = response.status;
        if status == StatusCode::UNAUTHORIZED || status == StatusCode::FORBIDDEN {
            let headers = response.headers.clone();
            let body = super::credentials::read_body(response, MAX_REQUEST_BODY)
                .await
                .unwrap_or_default();
            excluded.insert(candidate.id.clone(), true);
            // 401/403 from an upstream account is credential state, not quota
            // or transient capacity. Keep the error body out of persisted state
            // and route to a different upstream account if one exists.
            let mut reason = quota::extract_upstream_error_code(&body);
            if reason.is_empty() {
                reason = "account_auth_failed".to_string();
            }
            app.log_codex_verdict_for_http(
                &candidate.id,
                model,
                status,
                &headers,
                &body,
                "auth_failover",
            );
            failover_from.clone_from(&candidate.id);
            failover_outcome = "auth_failover".to_string();
            app.mark_account_auth_failure(&candidate.id, model, &reason);
            attempt += 1;
            continue;
        }
        if status == StatusCode::TOO_MANY_REQUESTS || status.is_server_error() {
            let headers = response.headers.clone();
            let gateway_body = super::credentials::read_body(response, MAX_REQUEST_BODY)
                .await
                .unwrap_or_default();
            // The gateway answers a model it cannot route with a 5xx, but
            // nothing about the account failed and no other identity can serve
            // a model the gateway does not know. Treated as an upstream failure
            // it marked healthy accounts unhealthy, swept the whole pool, and
            // told the caller its account had failed, for a request that can
            // never succeed. Answer the caller with the truth instead, and
            // leave account health alone.
            if quota::gateway_unknown_model(&gateway_body) {
                app.logger.printf(&format!(
                    "gateway cannot route model {model} requested by a client"
                ));
                write_openai_error(
                    writer,
                    StatusCode::NOT_FOUND,
                    "model_not_found",
                    "requested model is not available through this pool",
                );
                return;
            }
            let retry_after_header = header(&headers, "retry-after").to_string();
            let wait = retry_after_or_default(&retry_after_header, Duration::from_secs(60));
            let reason = if status == StatusCode::TOO_MANY_REQUESTS {
                "rate_limited"
            } else {
                "upstream_5xx"
            };
            app.log_codex_verdict_for_http(
                &candidate.id,
                model,
                status,
                &headers,
                &gateway_body,
                reason,
            );
            if status == StatusCode::TOO_MANY_REQUESTS {
                excluded.insert(candidate.id.clone(), true);
                capacity_excluded.insert(candidate.id.clone(), true);
                // Another identity is cheaper than any wait, so fail over
                // whenever one can still serve this model.
                if attempt + 1 < attempt_limit && app.has_preferred_account(model, &excluded) {
                    failover_from.clone_from(&candidate.id);
                    failover_outcome = "rate_limit_failover".to_string();
                    app.mark_failure(&candidate.id, model, reason, delta(wait));
                    attempt += 1;
                    continue;
                }
                // Nothing else can serve it. A 429 before any byte reaches the
                // caller is the same transient refusal the streaming path
                // already waits out, so spend a capacity round on the same
                // account rather than reporting "all eligible upstream accounts
                // failed" without ever waiting (a single-account pool got no
                // retry at all). Upstream's own Retry-After decides whether
                // waiting is honest: a header longer than the configured cap
                // describes a drained window rather than congestion, and
                // holding the caller for it would be worse than telling them
                // now. An absent header is not evidence of a long wait, so it
                // does not block the retry; the backoff paces those rounds.
                let advertised = retry_after_or_default(&retry_after_header, Duration::ZERO);
                if capacity_retries < tuning.capacity_retry_limit
                    && advertised <= tuning.capacity_retry_max_wait
                {
                    capacity_retries += 1;
                    // Deliberately no cooldown: cooling the account down here
                    // would make it unselectable for its own retry and strand
                    // the request on an empty pool. The failure is still
                    // recorded. Wait out whichever is longer: retrying before a
                    // Retry-After upstream just named would spend an attempt on
                    // a refusal it already promised.
                    app.mark_failure(&candidate.id, model, reason, TimeDelta::zero());
                    let delay = tuning
                        .capacity_retry_backoff_for(capacity_retries)
                        .max(advertised);
                    let (restored, waited) = spend_capacity_retry_round(
                        app,
                        model,
                        delay,
                        &mut excluded,
                        &mut capacity_excluded,
                        cancel.cancelled(),
                    )
                    .await;
                    if !waited {
                        throughput.cancelled = true;
                        return;
                    }
                    attempt += 1 - i64::try_from(restored).unwrap_or(0);
                    continue;
                }
                failover_from.clone_from(&candidate.id);
                failover_outcome = "rate_limit_failover".to_string();
                app.mark_failure(&candidate.id, model, reason, delta(wait));
                attempt += 1;
                continue;
            }
            let wait = retry_after_or_default(
                &retry_after_header,
                Duration::from_secs(u64::try_from(UPSTREAM_5XX_COOLDOWN_SECONDS).unwrap_or(10)),
            );
            if retry_after_header.trim().is_empty() {
                // A 5xx without Retry-After is a transient upstream/server
                // failure, not proof that the account is out of quota. Preserve
                // sticky account locality for KV cache hit rate: do not fail
                // over or cool down the selected account until repeated
                // failures show it is genuinely unhealthy. This keeps a single
                // blip from moving a hot route to a cold account.
                let consecutive = app.mark_failure(&candidate.id, model, reason, TimeDelta::zero());
                if consecutive < UPSTREAM_5XX_FAILOVER_AFTER {
                    write_openai_error(
                        writer,
                        StatusCode::BAD_GATEWAY,
                        "bad_gateway",
                        "selected upstream account failed transiently",
                    );
                    return;
                }
                excluded.insert(candidate.id.clone(), true);
                if !app.has_preferred_account(model, &excluded) {
                    write_openai_error(
                        writer,
                        StatusCode::BAD_GATEWAY,
                        "bad_gateway",
                        "selected upstream account failed repeatedly",
                    );
                    return;
                }
                failover_from.clone_from(&candidate.id);
                failover_outcome = "repeated_5xx_failover".to_string();
                app.mark_cooldown(&candidate.id, model, reason, delta(wait));
                attempt += 1;
                continue;
            }
            excluded.insert(candidate.id.clone(), true);
            failover_from.clone_from(&candidate.id);
            failover_outcome = "repeated_5xx_failover".to_string();
            app.mark_failure(&candidate.id, model, reason, delta(wait));
            attempt += 1;
            continue;
        }
        let response_headers = response.headers.clone();
        let info = if !convert_response && is_streaming(&response.headers) {
            let account_headers = app.current_account_response_headers(&candidate.id);
            let mut before_commit = |writer: &mut dyn ResponseWriter| {
                for (name, value) in &account_headers {
                    set_header(writer, name, value);
                }
                relay_native_codex_response_headers(writer, &response_headers, native);
                commit_proxy_response_headers(writer, status, &response_headers);
            };
            let mut reader = SseReader::new(response.body);
            let result = copy_streaming_proxy_response_with_precommit(
                writer,
                &mut reader,
                precommit_byte_limit(request.body.len()),
                &tuning,
                Some(&mut before_commit),
            )
            .await;
            let mut info = result.info;
            if result.retryable_terminal_failure
                && transient_overload_code(&info.terminal_error_code)
                && overload_retries < OVERLOAD_SAME_ACCOUNT_RETRY_LIMIT
            {
                // Upstream overload is the server's condition, not this
                // account's allowance, so the same account is retried after a
                // short backoff, as a native Codex (which has only one account)
                // does. Moving at once would split the main agent from its
                // subagents and throw away the account's KV cache, so the next
                // account pays a full prefill. Only when this schedule is spent
                // does the sweep below move the whole lineage. No cooldown
                // here: it would make the account unselectable for its own
                // retry.
                overload_retries += 1;
                app.mark_retryable_terminal_response_failure(&candidate.id, model, &info, false);
                if !cancel.sleep(tuning.overload_retry_backoff).await {
                    throughput.cancelled = true;
                    return;
                }
                continue;
            }
            if result.retryable_terminal_failure {
                excluded.insert(candidate.id.clone(), true);
                capacity_excluded.insert(candidate.id.clone(), true);
                // Account allowance failures (rate_limit_exceeded,
                // usage_not_included, insufficient_quota), server faults, and
                // an overload that outlasted the same-account schedule reach
                // here. The rule, in order, and the order is the point: sweep
                // every other available identity first with no wait, because
                // another account is always cheaper than any delay; only when
                // every one of them has refused, wait out one backoff round,
                // restore all of them, and sweep again from the top; each
                // round waits longer than the last. It ends when both the
                // identities and the schedule are spent, and only then does the
                // caller see the refusal. Do not reorder this into a
                // wait-per-account loop: that pays the schedule once per
                // identity instead of once per sweep.
                //
                // The buffered prefix has not changed the client-visible
                // response. Retry only when another real routing candidate and
                // another configured attempt remain; otherwise preserve the
                // original upstream SSE failure instead of replacing it with a
                // synthetic pool error.
                if attempt + 1 < attempt_limit && app.has_preferred_account(model, &excluded) {
                    failover_from.clone_from(&candidate.id);
                    failover_outcome =
                        stream_retry_failover_outcome(&info.terminal_failure_class).to_string();
                    app.mark_retryable_terminal_response_failure(&candidate.id, model, &info, true);
                    attempt += 1;
                    continue;
                }
                // No other upstream identity can serve this request. Capacity
                // is a transient model-level condition, so retry the same
                // account behind a short backoff rather than handing the caller
                // the upstream "at capacity" refusal on its first occurrence;
                // nothing client-visible has been written yet. A pool that
                // still has a healthy backup fails over above and never reaches
                // here, so this must not add latency to a pool with spare
                // identities. The retry budget is deliberately separate from
                // the per-account attempt budget: retrying the same account is
                // not another account attempt, so a single-account pool
                // (attempt limit 1) can still retry.
                if capacity_retries < tuning.capacity_retry_limit {
                    capacity_retries += 1;
                    // Deliberately no cooldown: it would make the account
                    // unselectable for its own retry and strand the request on
                    // an empty pool.
                    app.mark_retryable_terminal_response_failure(
                        &candidate.id,
                        model,
                        &info,
                        false,
                    );
                    let (restored, waited) = spend_capacity_retry_round(
                        app,
                        model,
                        tuning.capacity_retry_backoff_for(capacity_retries),
                        &mut excluded,
                        &mut capacity_excluded,
                        cancel.cancelled(),
                    )
                    .await;
                    if !waited {
                        throughput.cancelled = true;
                        return;
                    }
                    // Give back the attempts this capacity round consumed. The
                    // retry budget is bounded on its own, and charging the
                    // account-attempt budget as well would let a pool run out of
                    // attempts while it is still waiting for the blip to clear.
                    attempt += 1 - i64::try_from(restored).unwrap_or(0);
                    continue;
                }
                for (name, value) in app.current_account_response_headers(&candidate.id) {
                    set_header(writer, &name, &value);
                }
                relay_native_codex_response_headers(writer, &response_headers, native);
                commit_proxy_response_headers(writer, status, &response_headers);
                write_streaming_bytes(writer, &result.buffered);
            }
            info.request_id.clone_from(&request_id);
            Some(info)
        } else if convert_response {
            for (name, value) in app.current_account_response_headers(&candidate.id) {
                set_header(writer, &name, &value);
            }
            write_chat_from_response(writer, response, model, &tuning).await
        } else {
            for (name, value) in app.current_account_response_headers(&candidate.id) {
                set_header(writer, &name, &value);
            }
            relay_native_codex_response_headers(writer, &response_headers, native);
            copy_proxy_response(writer, response, &tuning).await
        };
        let Some(mut info) = info else {
            app.mark_failure(&candidate.id, model, "upstream_response_error", seconds(30));
            return;
        };
        info.request_id.clone_from(&request_id);
        info.failover_from_account_id.clone_from(&failover_from);
        info.failover_outcome.clone_from(&failover_outcome);
        throughput.completed_at = info.completed_at;
        throughput.usage = info.usage.clone();
        if matches!(
            info.terminal_event.as_str(),
            "error" | "response.failed" | "response.incomplete"
        ) {
            // A terminal error can reach here only after the pre-commit path
            // found no real fallback, after semantic SSE output was committed,
            // or when a standalone error was not capacity-retryable. Never
            // retry at this point: splicing a second stream could duplicate
            // work, tool effects, or response IDs and corrupt the SSE sequence.
            throughput.success = false;
            app.mark_terminal_response_failure(
                route,
                model,
                &candidate.id,
                &info,
                Some(throughput),
                true,
            );
            return;
        }
        // Account health treats a well-formed non-retryable upstream response
        // as a healthy connection, but client throughput success is stricter:
        // only a 2xx response belongs in the success numerator.
        throughput.success = status.is_success();
        app.mark_success_with_measurement(route, model, &candidate.id, &info, Some(throughput));
        return;
    }
    write_openai_error(
        writer,
        StatusCode::BAD_GATEWAY,
        "bad_gateway",
        "all eligible upstream accounts failed",
    );
}

/// An upstream condition that is the server's, not the account's: an
/// overload, or a server fault. Retrying the same account is the native
/// answer to these, moving to another account the answer to an account's own
/// allowance being spent. A native Codex retries server_error on its one
/// account (codex-api/src/sse/responses_error.rs parse_failed_response: it
/// falls to the default ApiError::Retryable branch). Moving on the first
/// server_error once carried a session off the expiring-credit accounts it
/// had been placed on, two faults in four minutes, under strict lineage
/// binding.
pub fn transient_overload_code(code: &str) -> bool {
    matches!(
        quota::sanitized_error_code(code).as_str(),
        "server_is_overloaded" | "slow_down" | "server_error" | "internal_server_error"
    )
}
