/// Why forwarding produced no upstream answer.
#[derive(Debug)]
pub enum ForwardError {
    /// The account's credential is unusable: quarantine it and fail over.
    Auth(String),
    /// Upstream could not be reached.
    Transport(String),
}

impl std::fmt::Display for ForwardError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Auth(detail) | Self::Transport(detail) => f.write_str(detail),
        }
    }
}

pub fn parse_model(value: &str) -> (String, String) {
    if let (Some(start), Some(end)) = (value.rfind('('), value.rfind(')'))
        && start > 0
        && end == value.len() - 1
    {
        let tier = &value[start + 1..end];
        if matches!(
            tier,
            "none" | "auto" | "minimal" | "low" | "medium" | "high" | "xhigh" | "max" | "ultra"
        ) {
            return (value[..start].to_string(), tier.to_string());
        }
    }
    (value.to_string(), String::new())
}

fn header<'a>(headers: &'a HeaderMap, name: &str) -> &'a str {
    super::http_io::header_value(headers, name)
}

pub fn request_operational_id(headers: &HeaderMap) -> String {
    ["x-request-id", "x-codex-request-id"]
        .into_iter()
        .map(|name| header(headers, name).trim())
        .find(|value| !value.is_empty())
        .map_or_else(super::crypto::random_id, str::to_string)
}

// ---- hosted tool conflicts ----

/// Hosted Responses tool types and the tool namespace the ChatGPT backend
/// reserves for each when such a tool is declared in the same request.
fn hosted_tool_namespace(tool_type: &str) -> Option<&'static str> {
    match tool_type {
        "image_generation" | "image_gen" => Some("image_gen"),
        "web_search" | "web_search_preview" => Some("web_search"),
        _ => None,
    }
}

/// Namespaces the ChatGPT Codex backend owns implicitly: the hosted twin is
/// attached server-side for current models even when the request declares no
/// hosted tool, so a client-declared twin always fails with "Function
/// 'image_gen.imagegen' conflicts with a hosted tool in the same request".
/// Verified against the live backend (2026-07), re-verified 2026-09-22 on
/// gpt-6-sol with Codex 0.156.1.
///
/// TODO(upstream): DELETE the "image_gen" entry once OpenAI fixes the Codex
/// client/hosted collision tracked in https://github.com/openai/codex/issues/28464
/// (their plan is to retire the hosted image tool in favor of the standalone
/// client extension, at which point this reservation would strip a then
/// legitimate client tool and disable image generation through the pool).
/// Verify by sending upstream an `additional_tools` input item declaring
/// {"type":"namespace","name":"image_gen","tools":[{"type":"function","name":
/// "imagegen",...}]}: while the bug exists it returns that 400; once it is
/// accepted, remove this entry, update SPEC.md 6.4.2, and keep the hosted-pair
/// dedupe below.
const ALWAYS_RESERVED_TOOL_NAMESPACES: &[&str] = &["image_gen"];

/// Removes client-declared tools whose name lives in a namespace the
/// upstream backend reserves, either implicitly or because the same request
/// also declares the hosted tool. Codex clients declare tools in two places,
/// the top-level `tools` array and (since Codex 0.144) `additional_tools`
/// items inside `input`; namespaced tools arrive as
/// `{"type":"namespace","name":...}` and upstream flattens their functions
/// into `namespace.function` names. Both locations and both shapes are
/// filtered, and the hosted capability is kept because upstream owns the
/// namespace either way. Do not simplify this into forwarding tools verbatim:
/// the conflict comes from the Codex client's experimental feature set, not
/// from user configuration, so the pool must stay tolerant.
pub fn drop_hosted_tool_conflicts(payload: &mut Map<String, Value>) {
    let mut reserved: Vec<String> = ALWAYS_RESERVED_TOOL_NAMESPACES
        .iter()
        .map(|name| (*name).to_string())
        .collect();
    if let Some(Value::Array(tools)) = payload.get("tools") {
        for tool in tools {
            let tool_type = tool.get("type").and_then(Value::as_str).unwrap_or_default();
            if let Some(namespace) = hosted_tool_namespace(tool_type) {
                reserved.push(namespace.to_string());
            }
        }
    }
    if let Some(Value::Array(tools)) = payload.get("tools")
        && let Some(filtered) = filter_reserved_tools(tools, &reserved)
    {
        payload.insert("tools".to_string(), Value::Array(filtered));
    }
    if let Some(Value::Array(input)) = payload.get_mut("input") {
        for item in input.iter_mut() {
            let Some(item) = item.as_object_mut() else {
                continue;
            };
            if item.get("type").and_then(Value::as_str) != Some("additional_tools") {
                continue;
            }
            if let Some(Value::Array(tools)) = item.get("tools")
                && let Some(filtered) = filter_reserved_tools(tools, &reserved)
            {
                item.insert("tools".to_string(), Value::Array(filtered));
            }
        }
    }
}

/// The tools without reserved ones, or None when nothing was removed.
fn filter_reserved_tools(tools: &[Value], reserved: &[String]) -> Option<Vec<Value>> {
    if tools.is_empty() {
        return None;
    }
    let filtered: Vec<Value> = tools
        .iter()
        .filter(|tool| {
            let tool_type = tool.get("type").and_then(Value::as_str).unwrap_or_default();
            if hosted_tool_namespace(tool_type).is_some() {
                return true;
            }
            let name = tool.get("name").and_then(Value::as_str).unwrap_or_default();
            let namespace = name.split_once('.').map(|(namespace, _)| namespace);
            !(reserved.iter().any(|item| item == name)
                || namespace.is_some_and(|ns| reserved.iter().any(|item| item == ns)))
        })
        .cloned()
        .collect();
    (filtered.len() != tools.len()).then_some(filtered)
}

